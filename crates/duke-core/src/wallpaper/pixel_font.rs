fn rows_of(character: char) -> &'static [&'static str; 7] {
    let wanted = character.to_ascii_uppercase();
    let found = GLYPHS.iter().find(|(glyph_character, _)| *glyph_character == wanted);
    let space = &GLYPHS.iter().find(|(glyph_character, _)| *glyph_character == ' ').expect("space glyph").1;
    found.map(|(_, rows)| rows).unwrap_or(space)
}

pub fn text_width(text: &str) -> i32 {
    let glyph_widths: i32 = text.chars().map(|character| rows_of(character)[0].len() as i32).sum();
    let gaps = (text.chars().count() as i32 - 1).max(0) * SPACE_BETWEEN_GLYPHS;
    glyph_widths + gaps
}

pub fn draw_text(canvas: &mut Canvas, left: i32, top: i32, text: &str, colour: Colour) {
    let mut x = left;
    for character in text.chars() {
        let rows = rows_of(character);
        for (row_index, row) in rows.iter().enumerate() {
            for (column_index, cell) in row.bytes().enumerate() {
                if cell == b'#' {
                    canvas.set_pixel(x + column_index as i32, top + row_index as i32, colour);
                }
            }
        }
        x += rows[0].len() as i32 + SPACE_BETWEEN_GLYPHS;
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_glyph_is_seven_rows_of_one_width() {
        for (character, rows) in GLYPHS {
            let width = rows[0].len();
            assert!(rows.iter().all(|row| row.len() == width), "{character:?} has rows of different widths");
            assert!(rows.iter().all(|row| row.bytes().all(|cell| cell == b'#' || cell == b'.')), "{character:?}");
        }
    }

    #[test]
    fn lower_case_reads_as_upper_case_and_unknown_characters_as_spaces() {
        assert_eq!(text_width("chapel"), text_width("CHAPEL"));
        assert_eq!(text_width("~"), text_width(" "));
        assert_eq!(text_width("I"), 3);
        assert_eq!(text_width("AB"), 11);
        assert_eq!(text_width(""), 0);
    }

    #[test]
    fn text_is_drawn_where_its_width_says() {
        let mut canvas = Canvas::new(40, 10);
        draw_text(&mut canvas, 2, 1, "HI", 0xFFFFFF);
        let lit_columns: Vec<i32> = (0..40).filter(|&x| (0..10).any(|y| canvas.pixel_at(x, y) == 0xFFFFFF)).collect();
        assert_eq!(lit_columns.first(), Some(&2));
        assert_eq!(lit_columns.last(), Some(&(2 + text_width("HI") - 1)));
    }
}
